// Generate CSS variables, the Tailwind theme and typed constants from the canonical tokens.json.
// Usage: node scripts/build-tokens.mjs [--check]   (--check fails if a committed output is stale)
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const web = resolve(here, "..");
const source = resolve(web, "../../assets/halt-package/02-design-system/tokens.json");
const tokens = JSON.parse(readFileSync(source, "utf8"));
const HEADER = "/* Generated by scripts/build-tokens.mjs from assets/halt-package/02-design-system/tokens.json. Do not edit. */\n";

const alias = (v) => (typeof v === "string" && /^\{.+\}$/.test(v) ? v.slice(1, -1) : null);
const cssValue = (v) => (alias(v) ? `var(--${alias(v)})` : String(v));

// Resolve a colour token to a literal for one theme (for JS consumers such as Cytoscape).
const colors = Object.fromEntries(tokens.color.tokens.map((t) => [t.name, t.value]));
function resolveColor(name, theme, seen = new Set()) {
  if (seen.has(name)) throw new Error(`alias cycle at ${name}`);
  seen.add(name);
  const raw = colors[name][theme];
  return alias(raw) ? resolveColor(alias(raw), theme, seen) : raw;
}

const flat = (group) => tokens[group].tokens.map((t) => [t.name, t.value]);
const fontVar = { display: "--font-archivo", mono: "--font-plex-mono" };
const families = Object.fromEntries(
  Object.entries(tokens.type.families).map(([k, v]) => [k, `var(${fontVar[k]}), ${v}`]),
);

function themeBlock(theme) {
  const lines = tokens.color.tokens.map((t) => `  --${t.name}: ${cssValue(t.value[theme])};`);
  for (const [name, value] of flat("shadow")) {
    lines.push(`  --${name}: ${typeof value === "object" ? value[theme] : value};`);
  }
  return lines.join("\n");
}

function shared() {
  const lines = [];
  for (const group of ["spacing", "radius", "borderWidth", "zIndex", "breakpoint", "maxWidth", "layout", "duration", "easing"]) {
    for (const [name, value] of flat(group)) lines.push(`  --${name}: ${value};`);
  }
  lines.push(`  --font-display: ${families.display};`, `  --font-mono: ${families.mono};`);
  return lines.join("\n");
}

function typeClasses() {
  const out = [];
  for (const group of tokens.type.groups) {
    for (const s of group.styles) {
      const family = s.family ?? group.family;
      out.push(
        `.${s.name} { font-family: var(--font-${family}); font-size: ${s.fontSize}; line-height: ${s.lineHeight}; ` +
          `font-weight: ${s.fontWeight}; letter-spacing: ${s.letterSpacing}; }`,
      );
    }
  }
  return out.join("\n");
}

const tokensCss =
  HEADER +
  `:root,\n:root[data-theme="dark"] {\n  color-scheme: dark;\n${themeBlock("dark")}\n}\n\n` +
  `:root[data-theme="light"] {\n  color-scheme: light;\n${themeBlock("light")}\n}\n\n` +
  `:root {\n${shared()}\n}\n\n` +
  `/* Type roles */\n${typeClasses()}\n`;

// Tailwind v4: drop the default palette and expose only HALT roles (AT-7.2: no stray hue).
// Theme keys never reuse a token's variable name, so no theme variable can refer to itself.
const themeCss =
  HEADER +
  "@theme inline {\n" +
  "  --color-*: initial;\n" +
  "  --color-transparent: transparent;\n" +
  "  --color-current: currentColor;\n" +
  tokens.color.tokens.map((t) => `  --color-${t.name}: var(--${t.name});`).join("\n") +
  "\n  --font-*: initial;\n  --font-ui: var(--font-display);\n  --font-data: var(--font-mono);\n" +
  "  --radius-*: initial;\n" +
  flat("radius").map(([n, v]) => `  --radius-${n.replace("radius-", "")}: ${v};`).join("\n") +
  "\n  --breakpoint-*: initial;\n" +
  flat("breakpoint").map(([n, v]) => `  --breakpoint-${n.replace("bp-", "")}: ${v};`).join("\n") +
  "\n  --spacing: 4px;\n  --shadow-*: initial;\n}\n";

const ms = (v) => Number(String(v).replace("ms", ""));
const bezier = (v) => (v === "linear" ? "linear" : v.replace(/cubic-bezier\(|\)/g, "").split(",").map(Number));
const tokensTs =
  "// Generated by scripts/build-tokens.mjs from tokens.json. Do not edit.\n" +
  "// Resolved literals for consumers that cannot read CSS variables (Cytoscape, canvas, motion).\n\n" +
  `export const color = ${JSON.stringify(
    {
      dark: Object.fromEntries(tokens.color.tokens.map((t) => [t.name, resolveColor(t.name, "dark")])),
      light: Object.fromEntries(tokens.color.tokens.map((t) => [t.name, resolveColor(t.name, "light")])),
    },
    null,
    2,
  )} as const;\n\n` +
  `export const duration = ${JSON.stringify(Object.fromEntries(flat("duration").map(([n, v]) => [n.replace("duration-", ""), ms(v)])), null, 2)} as const;\n\n` +
  `export const easing = ${JSON.stringify(Object.fromEntries(flat("easing").map(([n, v]) => [n.replace("ease-", ""), bezier(v)])), null, 2)} as const;\n\n` +
  `export const borderWidth = ${JSON.stringify(Object.fromEntries(flat("borderWidth").map(([n, v]) => [n, parseFloat(v)])), null, 2)} as const;\n\n` +
  "export type Theme = keyof typeof color;\nexport type ColorToken = keyof (typeof color)[\"dark\"];\n";

const outputs = {
  "src/styles/tokens.css": tokensCss,
  "src/styles/tailwind-theme.css": themeCss,
  "src/styles/tokens.ts": tokensTs,
};

const check = process.argv.includes("--check");
let stale = 0;
for (const [rel, text] of Object.entries(outputs)) {
  const path = resolve(web, rel);
  if (check) {
    let current = "";
    try {
      current = readFileSync(path, "utf8");
    } catch {}
    if (current !== text) {
      console.error(`${rel} is out of date; run: npm run gen:tokens`);
      stale += 1;
    }
  } else {
    writeFileSync(path, text);
    console.log(`wrote ${rel}`);
  }
}
process.exit(stale ? 1 : 0);
